"""Model structure: columns, constraints and relationship wiring.

Structural assertions only - the constraints are *exercised* against a real
Postgres in tests/integration/test_models_constraints.py, because a CHECK
that SQLAlchemy renders is not proof that Postgres enforces it.
"""

from __future__ import annotations

from typing import Any, cast

import pytest
from sqlalchemy import CheckConstraint, String, Table, UniqueConstraint
from sqlalchemy import Enum as SAEnum
from sqlalchemy.sql.schema import DefaultClause

from insight.db.base import Base
from insight.models import Membership, User, Workspace, WorkspaceRole


def table_of(model: Any) -> Table:
    """`__table__` is annotated as FromClause; every structural attribute we
    care about lives on Table."""
    return cast(Table, model.__table__)


def check_names(model: Any) -> set[str]:
    return {
        str(c.name)
        for c in table_of(model).constraints
        if isinstance(c, CheckConstraint) and c.name is not None
    }


def unique_names(model: Any) -> set[str]:
    return {
        str(c.name)
        for c in table_of(model).constraints
        if isinstance(c, UniqueConstraint) and c.name is not None
    }


def index_names(model: Any) -> set[str]:
    return {str(i.name) for i in table_of(model).indexes if i.name is not None}


class TestTableNames:
    @pytest.mark.parametrize(
        ("model", "name"),
        [(Workspace, "workspaces"), (User, "users"), (Membership, "memberships")],
    )
    def test_table_name(self, model: Any, name: str) -> None:
        assert model.__tablename__ == name

    def test_all_three_are_registered_on_the_metadata(self) -> None:
        """Alembic autogenerate drops anything missing from the metadata."""
        assert {"workspaces", "users", "memberships"} <= set(Base.metadata.tables)


class TestWorkspace:
    def test_slug_is_unique(self) -> None:
        assert table_of(Workspace).c.slug.unique is True

    def test_is_active_defaults_true_in_the_database(self) -> None:
        default = cast(DefaultClause, table_of(Workspace).c.is_active.server_default)
        assert default is not None
        assert "true" in str(default.arg).lower()

    def test_lowercase_and_blank_name_are_enforced(self) -> None:
        assert check_names(Workspace) == {
            "ck_workspaces_slug_is_lowercase",
            "ck_workspaces_name_not_blank",
        }


class TestUser:
    def test_email_length_allows_a_full_rfc5321_address(self) -> None:
        email_type = cast(String, table_of(User).c.email.type)
        assert email_type.length == 320

    def test_password_hash_is_nullable_for_sso_users(self) -> None:
        """A NOT NULL column would force a placeholder hash."""
        assert table_of(User).c.password_hash.nullable is True

    def test_email_column_is_not_plainly_unique(self) -> None:
        """Uniqueness is case-insensitive, via a functional index."""
        assert table_of(User).c.email.unique is not True

    def test_case_insensitive_unique_index_exists(self) -> None:
        assert "uq_users_email_lower" in index_names(User)

    def test_email_shape_is_constrained(self) -> None:
        assert check_names(User) == {
            "ck_users_email_is_lowercase",
            "ck_users_email_has_local_part",
        }

    def test_has_local_password_reflects_the_hash(self) -> None:
        assert User(password_hash="argon2...").has_local_password is True
        assert User(password_hash=None).has_local_password is False


class TestMembership:
    def test_one_membership_per_user_and_workspace(self) -> None:
        # Generated by the naming convention, not hand-written: an explicit
        # name would bypass the convention and make autogenerate noisy.
        assert "uq_memberships_workspace_id_user_id" in unique_names(Membership)

    def test_user_id_is_indexed_for_the_workspace_switcher(self) -> None:
        assert "ix_memberships_user_id" in index_names(Membership)

    @pytest.mark.parametrize("column", ["workspace_id", "user_id"])
    def test_foreign_keys_cascade(self, column: str) -> None:
        fk = next(iter(table_of(Membership).c[column].foreign_keys))
        assert fk.ondelete == "CASCADE"

    def test_role_defaults_to_member(self) -> None:
        default = cast(DefaultClause, table_of(Membership).c.role.server_default)
        assert default is not None
        assert "member" in str(default.arg)

    def test_role_enum_values(self) -> None:
        assert [r.value for r in WorkspaceRole] == [
            "owner",
            "admin",
            "member",
            "viewer",
        ]

    def test_role_is_a_native_postgres_enum(self) -> None:
        role_type = cast(SAEnum, table_of(Membership).c.role.type)
        assert role_type.name == "workspace_role"


class TestRelationships:
    @pytest.mark.parametrize(
        ("model", "attr"),
        [
            (Workspace, "memberships"),
            (User, "memberships"),
            (Membership, "workspace"),
            (Membership, "user"),
        ],
    )
    def test_lazy_loading_is_disabled(self, model: Any, attr: str) -> None:
        """lazy='raise' everywhere.

        An implicit lazy load inside an async session raises a confusing
        MissingGreenlet at runtime. Failing loudly at development time, with
        the attribute named, is far cheaper to debug.
        """
        assert model.__mapper__.relationships[attr].lazy == "raise"

    def test_membership_cascades_from_both_sides(self) -> None:
        for model in (Workspace, User):
            cascade = model.__mapper__.relationships["memberships"].cascade
            assert "delete-orphan" in cascade
